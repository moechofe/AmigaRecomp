class Session:
    def __init__(self, host, log: Log, statefile: Path | None = None):
        self.host, self.log = host, log
        self.statefile = statefile
        self.halted = False
        self.spool = ""                  # log text read while deciding whether to halt

    def key(self, name: str, hold: float = 0.0) -> None:
        """Press a key the *game* sees. The machine has to be running: a keypress into a
        halted emulation goes nowhere."""
        if name not in KEYS:
            raise SystemExit(f"unknown key {name!r} -- known: {' '.join(sorted(KEYS))}")
        self.resume()
        self.host.key(name, hold)

    def save_state(self, path: Path, timeout: float = 12.0) -> Path:
        """F8, then take the state out from under WinUAE's feet.

        `SPC_STATESAVE` writes back to whatever `-statefile=` named, so the run's own start
        state is what gets clobbered. A run that wants to keep one therefore starts from a
        disposable copy, and this copies the result out under its real name once the file
        has actually grown.
        """
        if self.statefile is None:
            raise SystemExit("--save needs --statefile: F8 writes back to the state the run "
                             "was launched from, and there is nothing to write back to")
        self.resume()
        was = self.statefile.stat().st_mtime if self.statefile.is_file() else 0
        deadline = time.time() + timeout
        while time.time() < deadline:
            self.host.save_key()
            time.sleep(1.0)
            if self.statefile.is_file() and self.statefile.stat().st_mtime > was:
                time.sleep(0.5)                       # let the emulator finish writing it
                path.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(self.statefile, path)
                print(f"  saved {path} ({path.stat().st_size} bytes)")
                return path
        raise OSError("the save key never wrote the state file")

    def click(self) -> None:
        """Click where the pointer already is. There is no acknowledgement: the machine
        may be running or about to halt on a breakpoint, and a click cannot tell."""
        self.resume()
        self.host.click()

    def press(self) -> None:
        """A click with no resume first: a script uses it to press into a halted machine."""
        self.host.click()

    def move(self, dx: int, dy: int) -> None:
        """Move the pointer by (dx, dy) host pixels, relative to where it is."""
        self.resume()
        self.host.move(dx, dy)

    def shot(self) -> Path | None:
        return take_screenshot(self.host)

    def halt(self, timeout: float = 12.0, retry: float = 2.5) -> None:
        """Shift+F12. Emulation stops the instant the console appears, which also stops it
        rendering: a screenshot cannot be taken while halted, so a shot is taken first.

        **Re-sent until the debugger answers**, the way take_screenshot re-sends F11: WinUAE
        drops an injected key every few dozen, and the one that matters most is the first one
        after launch, while the state is still being restored.

        **The machine also halts itself.** A breakpoint firing opens the console with nobody
        pressing anything, and the flag only follows that when the trigger lands inside a
        command's own reply window. So the log is read first and a trigger in it is taken as
        the acknowledgement. Without this, the next Shift+F12 goes into an open console and
        the run dies on the one after it.

        Entering the debugger writes a register dump to the -conlogfile, so the file growing
        is the acknowledgement. Its size is read off disk rather than through Log, which would
        consume the dump that belongs in the next command's reply.
        """
        if self.halted:
            return
        self.spool += self.log.read()
        if any(word in self.spool for word in TRIGGERS):
            self.halted = True
            return

        def written() -> int:
            return self.log.path.stat().st_size if self.log.path.is_file() else 0

        before, deadline = written(), time.time() + timeout
        while True:
            self.host.debugger_key()
            until = time.time() + retry
            while time.time() < until:
                time.sleep(0.2)
                if self.host.debugger_open(self.log.path, before):
                    time.sleep(0.2)
                    self.halted = True
                    return
            if time.time() >= deadline:
                raise TimeoutError(self.host.debugger_name + ". " + self.host.blind(
                    "The keys went out and the emulator wrote nothing back."))

    def resume(self) -> None:
        if not self.halted:
            return
        self.host.send("x")
        time.sleep(0.2)
        self.halted = False

    def command(self, line: str, wait: str | None = None, settle: float = 0.4) -> str:
        """One debugger command, and whatever the log says back.

        `g` resumes, so the halted flag has to follow it -- and a watchpoint or breakpoint
        firing halts the machine again without anyone pressing a key, which is what the
        trigger words below detect. Getting this wrong sends a Shift+F12 into an already
        open debugger and the session desynchronises.

        Whatever halt() read off the log while deciding is carried in `spool` and handed back
        with this command's reply, so a hit is printed once and never swallowed.
        """
        self.halt()
        self.host.send(line)
        if line.strip() in ("g", "x"):
            self.halted = False
        reply = self.spool + (self.log.wait_for(wait, 10.0) if wait
                              else (time.sleep(settle) or self.log.read()))
        self.spool = ""
        if any(word in reply for word in TRIGGERS):
            self.halted = True
        return reply

    def dump(self, path: Path, addr: int = 0, length: int = 0x80000) -> Path:
        """S <file> <addr> <n>. The path is unquoted in the debugger, so it must not have spaces.

        Absolute, because the debugger resolves a relative path against WinUAE's working
        directory and not this script's.
        """
        path = path.resolve()
        if " " in str(path):
            raise ValueError(f"the debugger's S command cannot take a path with spaces: {path}")
        path.parent.mkdir(parents=True, exist_ok=True)
        self.command(f"S {self.host.debugger_path(path)} {addr:X} {length:X}", wait="Wrote ")
        if not path.exists():
            raise OSError(f"the debugger claimed to write {path}, but it is not there")
        return path

    def wait_for_colours(self, want: int, timeout: float = 180.0) -> Path:
        """Take screenshots until one has exactly `want` distinct colours."""
        deadline = time.time() + timeout
        seen = []
        while time.time() < deadline:
            shot = self.shot()
            if shot is None:
                raise OSError("no screenshot appeared -- " + self.host.blind(
                    "the keys went out and the emulator wrote nothing; it was busy or "
                    "the keys missed"))
            count = colours(shot)
            seen.append(count)
            print(f"  {shot.name}: {count} colours" + ("  <-" if count == want else ""))
            if count == want:
                return shot
            time.sleep(1.0)
        raise TimeoutError(f"never saw {want} colours; saw {seen}")

    def keep_shot(self, shot: Path, name: str | None) -> Path:
        """Copy an emulator screenshot into reference/, under `name` (the emulator's own name if None)."""
        REFERENCE.mkdir(parents=True, exist_ok=True)
        target = REFERENCE / (f"{name}.png" if name else shot.name)
        shutil.copy(shot, target)
        print(f"  kept {target}")
        return target


# --- the session script ------------------------------------------------------------------------

def substitutions(out_dir: Path) -> dict[str, str]:
    """{out} and {df0} .. {df3} -- the paths a script cannot know and this machine can.

    The floppies are read from the `floppyN=` lines of the generated oracle.uae, or the
    `floppy_drive_N =` lines of the generated oracle.fs-uae.
    """
    values = {"{out}": str(out_dir)}
    for line in CONFIG.read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"floppy(?:_drive_)?([0-3])\s*=\s*(.*)", line.strip())
        if match and match.group(2):
            values[f"{{df{match.group(1)}}}"] = match.group(2)
    return values


def directive(session: Session, name: str, rest: str) -> None:
    """One `!` line. These drive the machine; the debugger cannot do any of them.

    Each one resumes first. A keypress into a halted emulation goes nowhere, and the
    machine has to be running for a screen to arrive at all -- which is the mistake that
    makes a script look like it did nothing.
    """
    session.resume()
    if name == "sleep":
        time.sleep(float(rest))
    elif name == "until":
        print(f"waiting for {rest} colours")
        session.wait_for_colours(int(rest))
    elif name == "shot":
        shot = session.shot()
        print(f"  shot: {shot.name if shot else 'none'}"
              + (f"  ({colours(shot)} colours)" if shot else ""))
        if shot:
            session.keep_shot(shot, rest.strip() or None)
    elif name == "save":
        session.save_state(Path(rest.strip()))
    elif name == "key":
        key, _, hold = rest.strip().lower().partition(" ")
        session.key(key, hold=float(hold) if hold else 0.0)
        print(f"  key {rest.strip()}")
    elif name == "click":
        if rest.strip():
            raise SystemExit("!click takes no arguments: it clicks where the pointer is")
        session.click()
        print("  click where the pointer is")
    elif name == "press":
        session.press()
        print("  press where the pointer is -- no acknowledgement")
    elif name == "move":
        try:
            dx, dy = (int(part) for part in rest.split())
        except ValueError:
            raise SystemExit("!move takes two integers: DX DY") from None
        session.move(dx, dy)
        print(f"  move {dx} {dy}")
    else:
        raise SystemExit(f"unknown script directive !{name}"
                         " -- known: !until !sleep !shot !settle !key !click !save !press !move")


def run_script(session: Session, lines: list[str], out_dir: Path, settle: float = 0.4) -> None:
    """A `!` line drives the machine, anything else is a debugger command.

    `!settle` is handled here rather than in directive(): it changes how long the next
    commands wait for the log and must not resume the machine.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    values = substitutions(out_dir)
    values["{out}"] = session.host.debugger_path(out_dir)
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        for key, value in values.items():
            line = line.replace(key, value)
        if line.startswith("!"):
            name, _, rest = line[1:].partition(" ")
            if name.lower() == "settle":
                settle = float(rest)
                print(f"  settle {settle:g}s")
                continue
            directive(session, name.lower(), rest.strip())
            continue
        print(f"  > {line}")
        reply = session.command(line, settle=settle)
        for text in reply.splitlines():
            if text.strip():
                print(f"    {text}")


def screensaver_warning() -> str | None:
    """How long this machine gives a run before it takes the input desktop away.

    `stay_awake` asks Windows to hold it off and Windows is entitled to refuse, so a run
    says out loud what it is racing. A screensaver that arms mid-run kills every injected
    event, and a secure resume then locks the machine, which no script can undo.
    """
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Control Panel\Desktop") as key:
            def value(name, fallback="0"):
                try:
                    return str(winreg.QueryValueEx(key, name)[0])
                except FileNotFoundError:
                    return fallback
            if value("ScreenSaveActive", "1") != "1":
                return None
            if not value("SCRNSAVE.EXE", "").strip():
                return None                  # a timeout with no `.scr` behind it starts nothing
            seconds = int(value("ScreenSaveTimeOut", "0") or 0)
            secure = value("ScreenSaverIsSecure", "0") == "1"
    except OSError:
        return None
    if not seconds:
        return None
    return (f"this machine's screensaver is set to {seconds} s"
            + (" with a secure resume, which locks it" if secure else "")
            + "; held off for the length of this run and restored afterwards. Do not use the "
              "machine while the run is injecting -- the keys go wherever the focus is")


def launch_winuae(statefile: Path | None = None) -> tuple[subprocess.Popen, Session]:
    exe = next((Path(p) for p in emulator.WINUAE_EXES if Path(p).is_file()), None)
    if exe is None:
        raise SystemExit("WinUAE is not installed in any of: " + ", ".join(emulator.WINUAE_EXES))
    if not CONFIG.is_file():
        raise SystemExit(f"no {CONFIG.relative_to(ROOT)} -- run tools/emulator.py first")
    CONLOG.parent.mkdir(parents=True, exist_ok=True)
    if CONLOG.exists():
        CONLOG.unlink()
    argv = [str(exe), "-f", str(CONFIG), "-conlogfile", str(CONLOG)]
    if statefile:
        # SPC_STATESAVE writes back to whatever -statefile named, so a run that also saves
        # will clobber this file. Pass a disposable copy when that matters.
        argv.append(f"-statefile={Path(statefile).resolve()}")
    process = subprocess.Popen(argv)
    print(f"launched WinUAE pid {process.pid}")

    emulation = None
    deadline = time.time() + 30
    while time.time() < deadline:
        found = windows_of(process.pid)
        emulation = found.get(EMULATION_CLASS)
        if emulation:
            break
        time.sleep(0.5)
    if not emulation:
        raise SystemExit("WinUAE's emulation window never appeared")
    host = WinHost(process.pid, emulation, screenshot_dir())
    return process, Session(host, Log(CONLOG), Path(statefile).resolve() if statefile else None)


def start_xvfb() -> tuple[subprocess.Popen, str]:
    """A private X server for FS-UAE, on a display number it picks and reports.

    The desktop's own server is no use: under Wayland it is Xwayland, which does not deliver
    XTEST input to a window the compositor has not focused. A private server has no window
    manager and no other client, so injected input has exactly one place to go, and the
    user's keyboard and mouse stay theirs.
    """
    exe = shutil.which("Xvfb")
    if exe is None:
        raise SystemExit("Xvfb is not on PATH -- install it (Debian/Ubuntu package xvfb)")
    read, write = os.pipe()
    server = subprocess.Popen([exe, "-displayfd", str(write), "-screen", "0", "1280x1024x24",
                               "-ac", "-nolisten", "tcp"], pass_fds=(write,),
                              stderr=subprocess.DEVNULL)
    os.close(write)
    number = os.read(read, 16).strip()      # written once the server is ready; empty if it died
    os.close(read)
    if not number:
        raise SystemExit("Xvfb did not start")
    return server, f":{number.decode()}"


def launch_fsuae(statefile: Path | None = None) -> tuple[subprocess.Popen, Session]:
    import pty
    import termios

    argv = emulator.fsuae_command()
    if argv is None:
        raise SystemExit("fs-uae is neither on PATH nor installed as a Flatpak "
                         f"({emulator.FSUAE_FLATPAK}) -- install FS-UAE")
    if not CONFIG.is_file():
        raise SystemExit(f"no {CONFIG.relative_to(ROOT)} -- run tools/emulator.py "
                         "--emulator fsuae first")
    build = CONFIG.parent
    shots, states = build / "shots", build / "states"
    shots.mkdir(parents=True, exist_ok=True)
    states.mkdir(parents=True, exist_ok=True)
    for old in shots.glob("*.png"):
        old.unlink()                       # tool-owned scratch: newest() must see only this run
    slot = states / "Saved State 1.uss"
    if statefile:
        shutil.copy(statefile, slot)
    if CONLOG.exists():
        CONLOG.unlink()

    xvfb, name = start_xvfb()
    process = None
    try:
        display = x11.Display(name)
        master, slave = pty.openpty()
        attrs = termios.tcgetattr(slave)
        attrs[3] &= ~termios.ECHO              # commands must not echo into replies
        termios.tcsetattr(slave, termios.TCSANOW, attrs)
        process = subprocess.Popen(argv + [str(CONFIG)], stdin=slave, stdout=slave,
                                   stderr=slave, cwd=ROOT,
                                   env={**os.environ, "DISPLAY": name,
                                        "SDL_VIDEODRIVER": "x11"})
        os.close(slave)
        print(f"launched FS-UAE pid {process.pid} on a private X server {name}")

        def drain() -> None:
            """Keep the pty empty, so FS-UAE never blocks on a full one, and log what it says."""
            with CONLOG.open("wb") as log:
                while True:
                    try:
                        chunk = os.read(master, 65536)
                    except OSError:
                        return
                    log.write(chunk)
                    log.flush()

        threading.Thread(target=drain, daemon=True).start()

        window, deadline = None, time.time() + 30
        while time.time() < deadline and window is None:
            window = display.window_of(process.pid, "FS-UAE")
            if window is None:
                time.sleep(0.5)
        if window is None:
            raise SystemExit("FS-UAE's window never appeared")
        display.activate(window)

        host = FsHost(process.pid, display, window, master, shots, xvfb)
        session = Session(host, Log(CONLOG), slot)
        if statefile:
            # F6 is ignored until the machine is running, and the window exists well before.
            for attempt in range(10):
                host.restore_key()
                try:
                    session.log.wait_for("savestate_quick slot=1 save=0", 3.0)
                    break
                except TimeoutError:
                    if attempt == 9:
                        raise
        return process, session
    except BaseException:
        if process is not None:
            FsHost.stop(process)
        xvfb.terminate()
        raise


def main() -> int:
    global CONFIG, CONLOG, REFERENCE
    parser = argparse.ArgumentParser(
        description="Drive the oracle emulator (WinUAE or FS-UAE): reach a screen, halt it, "
                    "dump memory, run debugger commands.")
    parser.add_argument("--game", required=True, metavar="ID", help="game folder under games/")
    parser.add_argument("--until", type=int, metavar="N",
                        help="poll screenshots until one has N distinct colours; "
                             "omit it when a --script owns the route")
    parser.add_argument("--name", help="reference/ file name for the --until screenshot "
                                       "(default: until-N)")
    parser.add_argument("--statefile", type=Path,
                        help="restore this save state at launch instead of cold-booting")
    parser.add_argument("--dumps", type=int, default=0, help="how many halt/dump cycles to run")
    parser.add_argument("--interval", type=float, default=1.0,
                        help="seconds of running between dumps")
    parser.add_argument("--out", type=Path,
                        help="prefix for the dumps; -NN.bin is appended "
                             "(default: games/<id>/reference/ramdump/capture)")
    parser.add_argument("--addr", type=lambda s: int(s, 0), default=0)
    parser.add_argument("--length", type=lambda s: int(s, 0), default=0x80000)
    parser.add_argument("--cmd", action="append", default=[],
                        help="a debugger command to run once halted; repeatable")
    parser.add_argument("--script", type=Path,
                        help="a session file: debugger commands one per line, plus the "
                             "directives !until !sleep !shot !settle !key !click !save !press "
                             "!move")
    parser.add_argument("--key", action="append", default=[],
                        help=f"press a key the game sees: {' '.join(sorted(KEYS))}; repeatable")
    parser.add_argument("--settle", type=float, default=0.4,
                        help="seconds to wait for the log after each command")
    parser.add_argument("--save", type=Path,
                        help="bank a save state here at the end of the run; WinUAE needs "
                             "--statefile, because F8 writes back to the state the run "
                             "started from")
    parser.add_argument("--emulator", choices=sorted(emulator.EMULATORS),
                        default=emulator.DEFAULT_EMULATOR,
                        help="oracle emulator (default: winuae on Windows, fsuae elsewhere)")
    parser.add_argument("--keep", action="store_true", help="leave the emulator running at the end")
    args = parser.parse_args()

    game = ROOT / "games" / args.game
    if not game.is_dir():
        print(f"error: no games/{args.game}/", file=sys.stderr)
        return 2
    CONFIG = ROOT / emulator.config_path(args.game, args.emulator)
    CONLOG = CONFIG.parent / ("condebug.log" if args.emulator == "winuae" else "console.log")
    REFERENCE = game / "reference"
    out = args.out or REFERENCE / "ramdump" / "capture"

    commands = list(args.cmd)
    if args.script:
        commands += args.script.read_text().splitlines()

    if args.emulator == "winuae":
        if sys.platform != "win32":
            print("capture.py drives WinUAE through the Win32 API and runs only on Windows; "
                  "on Linux use --emulator fsuae", file=sys.stderr)
            return 2
        bind_windows()
        armed = screensaver_warning()
        screensaver_was_on = stay_awake()
        if armed:
            print(f"! {armed}")
        awake = keep_awake()

        def restore() -> None:
            awake.set()
            stay_awake(on=not screensaver_was_on)

        desktop = clear_input_desktop()
        if desktop != "Default":
            restore()
            raise SystemExit(f"the input desktop is {desktop}, so nothing can be injected -- "
                             "unlock the machine and run it again")
        make_room(screenshot_dir())
        process, session = launch_winuae(args.statefile)
    else:
        if shutil.which("Xvfb") is None:
            print("capture.py --emulator fsuae runs FS-UAE on a private X server and needs "
                  "Xvfb on PATH", file=sys.stderr)
            return 2
        process, session = launch_fsuae(args.statefile)

        def restore() -> None:
            pass

    try:
        for name in args.key:
            session.key(name)
            print(f"pressed {name}")

        if args.until is not None:
            print(f"waiting for {args.until} colours")
            shot = session.wait_for_colours(args.until)
            session.keep_shot(shot, args.name or f"until-{args.until}")

        for index in range(args.dumps):
            # The screenshot comes first, and while the machine is still running: WinUAE
            # writes a screenshot on the next frame it renders, and a halted machine renders
            # none. So the pair is a shot and the dump one halt later, not one frame.
            shot = session.shot()
            path = session.dump(Path(f"{out}-{index:02d}.bin"), args.addr, args.length)
            print(f"  dump {index:02d}: {path.name}"
                  + (f"  ({colours(shot)} colours on screen)" if shot else "  (no screenshot)"))
            session.resume()
            time.sleep(args.interval)

        run_script(session, commands, out.parent, args.settle)

        if args.save:
            session.save_state(args.save)

        if not args.keep:
            session.resume()
    finally:
        restore()
        if not args.keep:
            time.sleep(0.5)
            session.host.close(process)
            print(f"{session.host.name} closed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
