# --- sending keys and clicks to the emulation window ----------------------------------------

class MOUSEINPUT(ctypes.Structure):
    _fields_ = [("dx", wintypes.LONG), ("dy", wintypes.LONG), ("mouseData", wintypes.DWORD),
                ("dwFlags", wintypes.DWORD), ("time", wintypes.DWORD),
                ("dwExtraInfo", ctypes.POINTER(ctypes.c_ulong))]


class KEYBDINPUT(ctypes.Structure):
    _fields_ = [("wVk", wintypes.WORD), ("wScan", wintypes.WORD), ("dwFlags", wintypes.DWORD),
                ("time", wintypes.DWORD), ("dwExtraInfo", ctypes.POINTER(ctypes.c_ulong))]


class INPUT(ctypes.Structure):
    class _VALUE(ctypes.Union):
        _fields_ = [("mi", MOUSEINPUT), ("ki", KEYBDINPUT)]

    _anonymous_ = ("value",)
    _fields_ = [("type", wintypes.DWORD), ("value", _VALUE)]


INPUT_MOUSE, INPUT_KEYBOARD = 0, 1
KEYEVENTF_KEYUP, KEYEVENTF_SCANCODE, KEYEVENTF_EXTENDEDKEY = 0x0002, 0x0008, 0x0001
MOUSEEVENTF_LEFTDOWN, MOUSEEVENTF_LEFTUP, MOUSEEVENTF_MOVE = 0x0002, 0x0004, 0x0001


def _key(scan: int, up: bool) -> INPUT:
    flags = KEYEVENTF_SCANCODE | (KEYEVENTF_KEYUP if up else 0)
    if scan in EXTENDED:
        flags |= KEYEVENTF_EXTENDEDKEY
    return INPUT(type=INPUT_KEYBOARD, ki=KEYBDINPUT(wVk=0, wScan=scan, dwFlags=flags,
                                                    time=0, dwExtraInfo=None))


def input_desktop() -> str:
    """Which desktop owns the input right now. Anything but `Default` and nothing can be
    injected: a screensaver, a lock screen and a disconnected session each take it away."""
    handle = user32.OpenInputDesktop(0, False, 0x0001)
    if not handle:
        return f"(cannot open: error {ctypes.get_last_error()})"
    name = ctypes.create_unicode_buffer(256)
    length = wintypes.DWORD()
    user32.GetUserObjectInformationW(handle, 2, name, 512, ctypes.byref(length))
    user32.CloseDesktop(handle)
    return name.value


def send_input(events: list) -> None:
    """Every injected event goes through here.

    A SendInput that delivers nothing is not a key WinUAE ignored: a screensaver may have
    switched the input desktop, and ERROR_ACCESS_DENIED looks exactly like an emulator that
    refuses injected input.
    """
    array = (INPUT * len(events))(*events)
    sent = user32.SendInput(len(events), array, ctypes.sizeof(INPUT))
    if sent == len(events):
        return
    error, desktop = ctypes.get_last_error(), input_desktop()
    raise OSError(f"SendInput delivered {sent} of {len(events)} events, error {error}; "
                  f"the input desktop is {desktop}"
                  + ("" if desktop == "Default" else
                     " -- dismiss the screensaver or unlock the machine and run it again"))


SPI_GETSCREENSAVEACTIVE, SPI_SETSCREENSAVEACTIVE, SPIF_SENDCHANGE = 0x0010, 0x0011, 0x0002
ES_CONTINUOUS, ES_DISPLAY_REQUIRED = 0x80000000, 0x00000002


def stay_awake(on: bool = True) -> bool:
    """Keep the screensaver from arming for the length of a run, and report what it was set to.

    A screensaver arming mid-run switches the input desktop, and every injected event after
    that fails with ERROR_ACCESS_DENIED, which looks exactly like WinUAE refusing injected
    input. Worse than a lost run: a secure resume leads to `Winlogon` and only a human can
    get the desktop back.

    Three requests, because one is not enough. `SPI_SETSCREENSAVEACTIVE` can be refused
    (error 329), so the registry value it would have written is written directly and the
    setting change broadcast; the execution state is asked for as well. `keep_awake()`
    covers what is left, since none of this resets an idle timer that has already run out.
    """
    was = wintypes.BOOL()
    user32.SystemParametersInfoW(SPI_GETSCREENSAVEACTIVE, 0, ctypes.byref(was), 0)
    user32.SystemParametersInfoW(SPI_SETSCREENSAVEACTIVE, 0 if on else 1, None, SPIF_SENDCHANGE)
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Control Panel\Desktop", 0,
                            winreg.KEY_READ | winreg.KEY_WRITE) as key:
            winreg.SetValueEx(key, "ScreenSaveActive", 0, winreg.REG_SZ, "0" if on else "1")
    except OSError:
        pass
    user32.SendMessageTimeoutW(0xFFFF, 0x001A, 0, "Windows", 0x0002, 1000, None)
    kernel32.SetThreadExecutionState(ES_CONTINUOUS | (ES_DISPLAY_REQUIRED if on else 0))
    return bool(was.value)


def keep_awake(every: float = 30.0) -> threading.Event:
    """Inject a zero-distance mouse move now and then, so the idle timer never expires.

    Zero distance because it must not move the Amiga pointer: WinUAE reads relative deltas,
    and (0, 0) is not one. Returns the event that stops it.
    """
    stop = threading.Event()

    def tick() -> None:
        while not stop.wait(every):
            if input_desktop() != "Default":
                continue
            try:
                send_input([INPUT(type=INPUT_MOUSE,
                                  mi=MOUSEINPUT(dx=0, dy=0, mouseData=0,
                                                dwFlags=MOUSEEVENTF_MOVE, time=0,
                                                dwExtraInfo=None))])
            except OSError:
                return

    threading.Thread(target=tick, daemon=True).start()
    return stop


def clear_input_desktop() -> str:
    """Take the input desktop back from a running screensaver, and say which one holds it.

    Killing the screensaver process is what returns the desktop to `Default`. Waking it with
    input does not: a secure resume lands on `Winlogon`, needs a password no script has, and
    cannot even be named -- `OpenInputDesktop` fails with error 5 there.
    """
    if input_desktop() == "Default":
        return "Default"
    listing = subprocess.run(["tasklist"], capture_output=True, text=True).stdout
    for line in listing.splitlines():
        if ".scr" in line.lower():
            for field in line.split():
                if field.isdigit():
                    subprocess.run(["taskkill", "/F", "/PID", field], capture_output=True)
                    break
    time.sleep(1.0)
    return input_desktop()


def activate(hwnd: int) -> bool:
    """Make the emulation window the foreground one, and say whether it worked.

    `SetForegroundWindow` alone is refused when the caller is not already the foreground
    process -- Windows answers success and does nothing, and the injected events then go to
    whatever *is* focused. Attaching to that window's input thread first is what makes it
    take. Without this, injected motion can still reach the Amiga while an injected button
    never does, because WinUAE only takes the mouse capture when it is active.
    """
    if user32.GetForegroundWindow() == hwnd:
        return True
    other = user32.GetForegroundWindow()
    mine = kernel32.GetCurrentThreadId()
    theirs = user32.GetWindowThreadProcessId(other, None) if other else 0
    if theirs:
        user32.AttachThreadInput(mine, theirs, True)
    user32.ShowWindow(hwnd, 9)
    user32.BringWindowToTop(hwnd)
    user32.SetForegroundWindow(hwnd)
    user32.SetActiveWindow(hwnd)
    if theirs:
        user32.AttachThreadInput(mine, theirs, False)
    time.sleep(0.15)
    return user32.GetForegroundWindow() == hwnd


def send_keys(hwnd: int, *scans: int, hold: float = 0.0) -> None:
    """Press the scancodes together and release them in reverse -- a chord, not a sequence.

    keybd_event with a zero scancode does not reach WinUAE: it reads RawInput, which needs
    a real scancode.

    `hold` is the gap between press and release. Zero works for the Amiga as well as for
    WinUAE's own hotkeys, so it stays the default.
    """
    activate(hwnd)
    time.sleep(0.05)
    send_input([_key(s, False) for s in scans])
    time.sleep(hold)
    send_input([_key(s, True) for s in reversed(scans)])


def mouse_click(hwnd: int, hold: float = 0.08) -> None:
    activate(hwnd)
    for flag in (MOUSEEVENTF_LEFTDOWN, MOUSEEVENTF_LEFTUP):
        send_input([INPUT(type=INPUT_MOUSE,
                          mi=MOUSEINPUT(dx=0, dy=0, mouseData=0, dwFlags=flag, time=0,
                                        dwExtraInfo=None))])
        time.sleep(hold)


def windows_of(pid: int) -> dict[str, int]:
    """Class name -> handle, for this process's visible top-level windows."""
    found: dict[str, int] = {}

    @ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)
    def visit(hwnd, _lparam):
        owner = wintypes.DWORD()
        user32.GetWindowThreadProcessId(hwnd, ctypes.byref(owner))
        if owner.value == pid and user32.IsWindowVisible(hwnd):
            name = ctypes.create_unicode_buffer(256)
            user32.GetClassNameW(hwnd, name, 256)
            found.setdefault(name.value, hwnd)
        return True

    user32.EnumWindows(visit, 0)
    return found


# --- talking to the debugger console ---------------------------------------------------------

class KEY_EVENT_RECORD(ctypes.Structure):
    class _CHAR(ctypes.Union):
        _fields_ = [("UnicodeChar", wintypes.WCHAR), ("AsciiChar", ctypes.c_char)]

    _fields_ = [("bKeyDown", wintypes.BOOL), ("wRepeatCount", wintypes.WORD),
                ("wVirtualKeyCode", wintypes.WORD), ("wVirtualScanCode", wintypes.WORD),
                ("uChar", _CHAR), ("dwControlKeyState", wintypes.DWORD)]


class INPUT_RECORD(ctypes.Structure):
    class _EVENT(ctypes.Union):
        _fields_ = [("KeyEvent", KEY_EVENT_RECORD)]

    _fields_ = [("EventType", wintypes.WORD), ("Event", _EVENT)]


KEY_EVENT = 0x0001
GENERIC_READ, GENERIC_WRITE = 0x80000000, 0x40000000
FILE_SHARE_READ, FILE_SHARE_WRITE = 1, 2
OPEN_EXISTING = 3
INVALID_HANDLE = ctypes.c_void_p(-1).value


def _record(char: str, down: bool) -> INPUT_RECORD:
    vk = user32.VkKeyScanW(char) & 0xFF
    scan = user32.MapVirtualKeyW(vk, 0)
    key = KEY_EVENT_RECORD(bKeyDown=down, wRepeatCount=1, wVirtualKeyCode=vk,
                           wVirtualScanCode=scan, dwControlKeyState=0)
    key.uChar.UnicodeChar = char
    return INPUT_RECORD(EventType=KEY_EVENT, Event=INPUT_RECORD._EVENT(KeyEvent=key))


def send_command(pid: int, line: str) -> None:
    """Type one debugger command, as if at the `>` prompt.

    WinUAE calls AllocConsole and reads with ReadConsoleInputW, so a script can write
    straight into its input buffer -- no window focus, no scancodes. A process can own only
    one console, hence the FreeConsole either side.

    A command sent while the machine is running is queued, not lost; it executes at the next
    breakpoint. So silence in the log means the breakpoint has not fired, not that the
    command failed.
    """
    kernel32.FreeConsole()
    if not kernel32.AttachConsole(pid):
        raise OSError("cannot attach to WinUAE's console -- is the debugger open? "
                      "It opens on Shift+F12, not with -debug or use_debugger=true.")
    try:
        handle = kernel32.CreateFileW("CONIN$", GENERIC_READ | GENERIC_WRITE,
                                      FILE_SHARE_READ | FILE_SHARE_WRITE, None,
                                      OPEN_EXISTING, 0, None)
        if handle == INVALID_HANDLE:
            raise OSError("cannot open CONIN$")
        try:
            events = []
            for char in line + "\r":
                events.append(_record(char, True))
                events.append(_record(char, False))
            array = (INPUT_RECORD * len(events))(*events)
            written = wintypes.DWORD()
            if not kernel32.WriteConsoleInputW(handle, array, len(events),
                                               ctypes.byref(written)):
                raise OSError("WriteConsoleInputW failed")
        finally:
            kernel32.CloseHandle(handle)
    finally:
        kernel32.FreeConsole()


class Log:
    """The -conlogfile, read incrementally. Python's open() shares the file; ReadAllText does not."""

    def __init__(self, path: Path):
        self.path, self.pos = path, 0

    def read(self) -> str:
        if not self.path.is_file():
            return ""
        with self.path.open("r", encoding="latin-1", errors="replace") as handle:
            handle.seek(self.pos)
            text = handle.read()
            self.pos = handle.tell()
        return text

    def wait_for(self, needle: str, timeout: float = 10.0) -> str:
        """Read until `needle` shows up, or raise. Returning the log unmatched would let a
        caller treat a debugger error as the reply it asked for."""
        seen, deadline = "", time.time() + timeout
        while time.time() < deadline:
            seen += self.read()
            if needle in seen:
                return seen
            time.sleep(0.15)
        raise TimeoutError(f"{needle!r} never appeared in {timeout:g}s; log said: {seen.strip()!r}")


