def make_room(folder: Path, headroom: int = 200) -> int:
    """Move old screenshots aside, because WinUAE's counter stops at 999.

    The name is `<disk>_NNN.png` with three digits, and once `_999` exists WinUAE writes
    **nothing at all** and says nothing about it. From a script that looks exactly like an
    emulator ignoring the screenshot key.

    **Clearing only at 999 is too late**: a run that starts at 979 fails halfway through
    with no screenshot. So the attic is used whenever fewer than `headroom` numbers are
    left, which costs one directory rename and buys a whole run.
    """
    shots = sorted(folder.glob("*.png"))
    used = [int(shot.stem[-3:]) for shot in shots
            if shot.stem[-4] == "_" and shot.stem[-3:].isdigit()]
    if not used or max(used) < 999 - headroom:
        return 0
    attic = folder / f"before-{time.strftime('%Y%m%d-%H%M%S')}"
    attic.mkdir(exist_ok=True)
    for shot in shots:
        shot.rename(attic / shot.name)
    print(f"moved {len(shots)} screenshots into {attic.name}: "
          f"WinUAE's counter had reached {max(used)} of 999")
    return len(shots)


def newest(folder: Path, after: float) -> Path | None:
    shots = [p for p in folder.glob("*.png") if p.stat().st_mtime > after]
    return max(shots, key=lambda p: p.stat().st_mtime) if shots else None


def take_screenshot(host, timeout: float = 15.0, retry: float = 3.0) -> Path | None:
    """The host's screenshot key, re-sent every `retry` seconds until a file lands.

    F11, not END+PrintScreen: Windows binds bare PrintScreen to the Snipping Tool, and its
    overlay takes the foreground out from under the next injected key. The config templates
    map F11 to the same event; END+PrintScreen still works if that mapping is ever absent.

    WinUAE drops an injected F11 every few dozen presses, with SendInput reporting success
    and the foreground never lost, so one press per screenshot is not enough for a long run.

    A file that exists may still be growing: the emulator writes the PNG from another thread.
    It counts once its size is non-zero and unchanged across 0.1 s.
    """
    mark = time.time() - 0.5
    deadline = time.time() + timeout
    nudge = 0.0
    while time.time() < deadline:
        if time.time() >= nudge:
            host.screenshot_key()
            nudge = time.time() + retry
        shot = newest(host.shots, mark)
        if shot and shot.stat().st_size > 0:
            size = shot.stat().st_size
            time.sleep(0.1)
            if shot.stat().st_size == size:
                return shot
            continue
        time.sleep(0.2)
    return None


def colours(shot: Path) -> int:
    return len(pixdiff.read_png(shot).colours())


# --- the two hosts: how each emulator is reached ------------------------------------------------

class WinHost:
    """WinUAE through the Win32 API."""
    name = "WinUAE"
    debugger_name = "Shift+F12 never opened WinUAE's debugger console"

    def __init__(self, pid: int, hwnd: int, shots: Path):
        self.pid, self.hwnd, self.shots = pid, hwnd, shots

    def key(self, name: str, hold: float = 0.0) -> None:
        send_keys(self.hwnd, KEYS[name], hold=hold)

    def screenshot_key(self) -> None:
        send_keys(self.hwnd, SC_F11)

    def save_key(self) -> None:
        send_keys(self.hwnd, SC_F8)

    def debugger_key(self) -> None:
        send_keys(self.hwnd, SC_SHIFT, SC_F12)

    def debugger_open(self, log: Path, before: int) -> bool:
        """Entering the debugger writes a register dump to the -conlogfile, so the file
        growing is the acknowledgement."""
        return (log.stat().st_size if log.is_file() else 0) > before \
            or CONSOLE_CLASS in windows_of(self.pid)

    def click(self, hold: float = 0.08) -> None:
        mouse_click(self.hwnd, hold)

    def move(self, dx: int, dy: int) -> None:
        raise SystemExit("!move needs --emulator fsuae: this tool never measured WinUAE "
                         "pointer motion")

    def send(self, line: str) -> None:
        send_command(self.pid, line)

    def debugger_path(self, path: Path) -> str:
        return str(path)

    def blind(self, otherwise: str) -> str:
        if user32.GetForegroundWindow() == 0:
            return "this shell has no interactive desktop, so SendInput cannot reach WinUAE at all"
        return otherwise

    def close(self, process: subprocess.Popen) -> None:
        process.terminate()


class FsHost:
    """FS-UAE through X11 XTEST and a pty on its stdin and stdout."""
    name = "FS-UAE"
    debugger_name = ("Pause never opened FS-UAE's console debugger "
                     "(console_debugger = 1, keyboard_key_pause = action_enter_debugger)")

    def __init__(self, pid: int, display: x11.Display, window: int, master_fd: int,
                 shots: Path, xvfb: subprocess.Popen):
        self.pid, self.display, self.window = pid, display, window
        self.master_fd, self.shots, self.xvfb = master_fd, shots, xvfb

    def key(self, name: str, hold: float = 0.0) -> None:
        self.display.activate(self.window)
        self.display.chord([KEYSYMS[name]], hold)

    def screenshot_key(self) -> None:
        self.display.chord(["F11"])

    def save_key(self) -> None:
        self.display.chord(["F8"])

    def restore_key(self) -> None:
        self.display.chord(["F6"])

    def debugger_key(self) -> None:
        self.display.chord(["Pause"])

    def debugger_open(self, log: Path, before: int) -> bool:
        """The `>` prompt is the acknowledgement. The log growing is not: FS-UAE prints
        other lines to stdout too."""
        if not log.is_file():
            return False
        with log.open("rb") as handle:
            handle.seek(before)
            return handle.read().rstrip().endswith(b">")

    def click(self, hold: float = 0.08) -> None:
        self.display.activate(self.window)
        self.display.button(1, hold)

    def move(self, dx: int, dy: int) -> None:
        self.display.move(dx, dy)

    def send(self, line: str) -> None:
        if len(line) > 99:
            raise SystemExit(f"FS-UAE's debugger reads 99 characters a line and would cut "
                             f"this one at {len(line)}: {line!r}")
        os.write(self.master_fd, line.encode() + b"\n")

    def debugger_path(self, path: Path) -> str:
        """Relative to the folder FS-UAE was started in: an absolute path is too long for the
        99-character line."""
        return os.path.relpath(path, ROOT)

    def blind(self, otherwise: str) -> str:
        return (f"no injected X event reached FS-UAE window 0x{self.window:x} on "
                f"DISPLAY={self.display.name}; " + otherwise)

    def close(self, process: subprocess.Popen) -> None:
        """End FS-UAE through its own quit key, then by force, then the X server."""
        self.display.chord(["End"])
        try:
            process.wait(5)
        except subprocess.TimeoutExpired:
            self.stop(process)
        self.xvfb.terminate()

    @staticmethod
    def stop(process: subprocess.Popen) -> None:
        """Under Flatpak, ending the `flatpak run` process does not end the sandbox."""
        argv = emulator.fsuae_command()
        if argv and Path(argv[0]).name == "flatpak":
            subprocess.run([argv[0], "kill", emulator.FSUAE_FLATPAK], capture_output=True)
        process.terminate()


