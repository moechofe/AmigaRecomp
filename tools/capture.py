#!/usr/bin/env python3
"""Drive the oracle emulator (WinUAE or FS-UAE) from a script: reach a screen, halt it, and
bring back dumps and screenshots.

Reference shots and machine-state measurements are taken under the oracle at moments nobody
can hit by hand. This tool launches the oracle configuration generated by tools/emulator.py
and drives it.

Two channels, and they are not interchangeable:

  * the emulation window: WinUAE reads RawInput, so keys go in with SendInput and real
    scancodes; FS-UAE reads X events, so keys go in with XTEST (tools/x11.py)
  * the debugger console: WinUAE's is a real console, so commands go in with
    WriteConsoleInputW and the replies come back through -conlogfile; FS-UAE's is its own
    stdin and stdout, so a pty carries both and its output is logged to console.log

    python tools/capture.py --game <id> --script run.dbg
    python tools/capture.py --game <id> --until 16 --name title
    python tools/capture.py --game <id> --until 16 --cmd e --cmd "S {out}/ram.bin 0 80000"

A --script is a session, not just a list of debugger commands: lines starting with `!`
drive the machine -- `!until <colours>`, `!sleep <n>`, `!shot [name]`, `!key <name>`,
`!click`, `!press`, `!move <dx> <dy>` -- or change how long a reply is waited for --
`!settle <seconds>` -- and everything else goes to the debugger. In a script, {out} is the
dump folder and {df0} .. {df3} are the floppy images named in the generated config.

Under WinUAE, keys and clicks need two things: the input desktop has to be `Default` -- a
running screensaver switches it and every SendInput call then fails with ERROR_ACCESS_DENIED
-- and the emulation window has to hold the foreground, because an injected key goes to
whatever is focused. FS-UAE runs on a private Xvfb server that nothing else uses, so its input
never competes with the desktop and the user's keyboard and mouse stay free.

**Poll for the screen; never sleep a fixed number of seconds.** A cold boot takes a variable
time. `--until N` and `!until N` wait for a screenshot with N distinct colours.

Dumps land under games/<id>/reference/ramdump/ and screenshots under games/<id>/reference/;
both are gitignored, like every other byte that came off the disks.

WinUAE runs on Windows only (Win32 API); FS-UAE needs Xvfb, and fs-uae on PATH or as a
Flatpak. `--help` works everywhere.
"""

